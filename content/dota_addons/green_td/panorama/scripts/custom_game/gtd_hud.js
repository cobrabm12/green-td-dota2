"use strict";

var GTD = GameUI.CustomUIConfig().gtd;   // tower data generated by tools/gen.py (gtd_data.js)

var SLOT_COLORS = {
	red: "#ff0303", blue: "#0042ff", teal: "#1ce6b9", purple: "#540081", yellow: "#fffc01",
	orange: "#fe8a0e", green: "#20c000", pink: "#e55bb0", gray: "#959697"
};

var KIND_TEXT = { air: "Air", immune: "Immune", hero: "Hero", boss: "Boss", normal: "" };

var selectedTower = -1;

// ---------------------------------------------------------------- helpers
function FormatNumber(n) {
	n = Math.floor(n);
	var s = String(n);
	return s.replace(/\B(?=(\d{3})+(?!\d))/g, " ");
}

function FormatTime(sec) {
	sec = Math.max(0, Math.ceil(sec));
	var m = Math.floor(sec / 60);
	var s = sec % 60;
	return m + ":" + (s < 10 ? "0" : "") + s;
}

function ShowError(text) {
	GameEvents.SendEventClientSide("dota_hud_error_message", { splitscreenplayer: 0, reason: 80, message: text });
}

// ---------------------------------------------------------------- top bar / board
function UpdateGame() {
	var st = CustomNetTables.GetTableValue("gtd_game", "state");
	if (!st) {
		return;
	}
	var waveText = st.wave > 0 ? ("Wave " + st.wave + " / " + st.total) : "Green TD";
	$("#WaveLabel").text = waveText;
	$("#WaveKind").text = st.wave > 0 ? (KIND_TEXT[st.kind] || "") : "";
	$("#ChancesLabel").text = "Chances: " + st.chances;
	$("#BoardLevel").text = String(st.wave);
	$("#BoardChances").text = String(st.chances);
	$.GetContextPanel().nextAt = st.next_at;
}

function UpdateTimer() {
	var nextAt = $.GetContextPanel().nextAt;
	var label = $("#TimerLabel");
	if (nextAt !== undefined && nextAt > 0 && nextAt > Game.GetGameTime()) {
		var st = CustomNetTables.GetTableValue("gtd_game", "state");
		var prefix = (st && st.wave > 0) ? "Next wave in " : "Game Starts in >>> ";
		label.text = prefix + FormatTime(nextAt - Game.GetGameTime());
	} else {
		label.text = "";
	}
	$.Schedule(0.2, UpdateTimer);
}

function UpdateBoard() {
	var container = $("#BoardPlayers");
	var ids = Game.GetAllPlayerIDs();
	for (var i = 0; i < ids.length; i++) {
		var pid = ids[i];
		var row = container.FindChildTraverse("P" + pid);
		if (!row) {
			row = $.CreatePanel("Panel", container, "P" + pid);
			row.AddClass("BoardRow");
			$.CreatePanel("Label", row, "Name").AddClass("BoardName");
			$.CreatePanel("Label", row, "Kills").AddClass("BoardValue");
		}
		var data = CustomNetTables.GetTableValue("gtd_players", String(pid)) || {};
		var name = row.FindChildTraverse("Name");
		name.text = Players.GetPlayerName(pid);
		name.style.color = SLOT_COLORS[data.color] || "#ffffff";
		row.FindChildTraverse("Kills").text = String(data.kills || 0);
		row.SetHasClass("Left", data.left === 1);
	}
}

function UpdateGold() {
	var data = CustomNetTables.GetTableValue("gtd_players", String(Players.GetLocalPlayer())) || {};
	$("#GoldLabel").text = FormatNumber(data.gold || 0);
	UpdateTowerButtons();
}

function MyGold() {
	var data = CustomNetTables.GetTableValue("gtd_players", String(Players.GetLocalPlayer())) || {};
	return data.gold || 0;
}

// ---------------------------------------------------------------- build menu
function BuildMenu() {
	var container = $("#BuildButtons");
	container.RemoveAndDeleteChildren();
	GTD.roots.forEach(function (id) {
		var t = GTD.towers[id];
		var btn = $.CreatePanel("Button", container, "Build_" + id);
		btn.AddClass("GtdButton");
		btn.AddClass("BuildButton");
		var key = $.CreatePanel("Label", btn, "");
		key.AddClass("HotkeyLabel");
		key.text = t.build_key || "";
		var name = $.CreatePanel("Label", btn, "");
		name.AddClass("BuildName");
		name.text = t.name;
		var cost = $.CreatePanel("Label", btn, "");
		cost.AddClass("BuildCost");
		cost.text = FormatNumber(t.cost);
		btn.SetPanelEvent("onactivate", function () { StartBuild(id); });
		btn.SetPanelEvent("onmouseover", function () {
			$.DispatchEvent("DOTAShowTextTooltip", btn, TooltipHtml(t));
		});
		btn.SetPanelEvent("onmouseout", function () { $.DispatchEvent("DOTAHideTextTooltip", btn); });
	});
}

function StartBuild(id) {
	var t = GTD.towers[id];
	if (MyGold() < t.cost) {
		ShowError("Not enough gold");
		return;
	}
	var hero = Players.GetPlayerHeroEntityIndex(Players.GetLocalPlayer());
	if (hero === -1) {
		return;
	}
	var ability = Entities.GetAbilityByName(hero, "gtd_build");
	if (ability === -1) {
		return;
	}
	GameEvents.SendCustomGameEventToServer("gtd_build_select", { tower: id });
	GameUI.SelectUnit(hero, false);
	Abilities.ExecuteAbility(ability, hero, false);
}

// ---------------------------------------------------------------- selected tower
function TowerTooltip(t) {
	var lines = [t.name, t.desc];
	if (t.attack) {
		var a = t.attack;
		var min = a.base + a.dice, max = a.base + a.dice * a.sides;
		lines.push("Damage: " + FormatNumber(min) + (max !== min ? " - " + FormatNumber(max) : "") + " (" + a.type + ")");
		lines.push("Cooldown: " + a.cooldown + "s   Range: " + a.range);
		lines.push("Targets: " + (a.air && a.ground ? "air + ground" : (a.air ? "air only" : "ground only")));
		if (a.splash) {
			lines.push("Splash: " + a.splash.full + " / " + a.splash.medium + " / " + a.splash.small);
		}
		if (a.bounce) {
			lines.push("Bounces: " + a.bounce.targets);
		}
	}
	if (t.multishot) { lines.push("Hits " + t.multishot.targets + " units per attack"); }
	if (t.poison) { lines.push("Slow poison: " + t.poison.dps + " dps, " + Math.round(t.poison.slow * 100) + "% slow"); }
	if (t.frost) { lines.push("Frost: " + Math.round(t.frost.slow * 100) + "% slow, " + t.frost.duration + "s"); }
	if (t.immolation) { lines.push("Burns " + FormatNumber(t.immolation.dps) + " dps in " + t.immolation.radius); }
	if (t.crits) { t.crits.forEach(function (c) { lines.push("Critical: " + c.chance + "% x" + c.mult); }); }
	if (t.bash) { lines.push("Bash: " + t.bash.chance + "% +" + t.bash.bonus + " (ground)"); }
	if (t.auras) {
		t.auras.forEach(function (au) {
			var kind = au.kind === "speed" ? "attack speed" : "damage";
			lines.push("Aura: +" + Math.round(au.value * 100) + "% " + kind + " (" + au.radius + ")");
		});
	}
	lines.push("Cost: " + FormatNumber(t.cost) + "   Sells for: " + FormatNumber(t.sell));
	return lines.join("\n");
}

// Text tooltips are rendered as HTML: one line per stat.
function TooltipHtml(t) {
	return TowerTooltip(t).split("\n").join("<br>");
}

function OnSelectionChanged() {
	var ent = Players.GetLocalPlayerPortraitUnit();
	var id = GTD.unit_to_tower[Entities.GetUnitName(ent)];
	var panel = $("#TowerPanel");
	if (!id) {
		selectedTower = -1;
		panel.AddClass("Hidden");
		return;
	}
	selectedTower = ent;
	var t = GTD.towers[id];
	var mine = Entities.GetPlayerOwnerID(ent) === Players.GetLocalPlayer();
	panel.RemoveClass("Hidden");
	$("#TowerName").text = t.name;
	$("#TowerDesc").text = t.desc;
	$("#TowerStats").text = TowerTooltip(t).split("\n").slice(2).join("\n");

	var container = $("#UpgradeButtons");
	container.RemoveAndDeleteChildren();
	(t.upgrades || []).forEach(function (up) {
		var u = GTD.towers[up];
		if (!u) { return; }
		var btn = $.CreatePanel("Button", container, "Up_" + up);
		btn.AddClass("GtdButton");
		btn.AddClass("UpgradeButton");
		btn.costValue = u.cost;
		var key = $.CreatePanel("Label", btn, "");
		key.AddClass("HotkeyLabel");
		key.text = (t.upgrade_keys && t.upgrade_keys[up]) || "";
		var label = $.CreatePanel("Label", btn, "");
		label.text = "Upgrade: " + u.name + "  (" + FormatNumber(u.cost) + ")";
		btn.enabled = mine;
		btn.SetPanelEvent("onactivate", function () { DoUpgrade(up); });
		btn.SetPanelEvent("onmouseover", function () { $.DispatchEvent("DOTAShowTextTooltip", btn, TooltipHtml(u)); });
		btn.SetPanelEvent("onmouseout", function () { $.DispatchEvent("DOTAHideTextTooltip", btn); });
	});
	$("#SellButton").enabled = mine;
	$("#SellLabel").text = "Sell (+" + FormatNumber(t.sell) + ")";
	UpdateTowerButtons();
}

function DoUpgrade(up) {
	var u = GTD.towers[up];
	if (selectedTower === -1 || !u) { return; }
	if (MyGold() < u.cost) { ShowError("Not enough gold"); return; }
	GameEvents.SendCustomGameEventToServer("gtd_upgrade", { entindex: selectedTower, to: up });
}

// ---------------------------------------------------------------- hotkeys
// Builder selected: the WC3 build keys (S Siege, P Poison, M Multishot, ...). One of your towers selected:
// the key of an upgrade (WC3 used the family letter: S upgrades a Siege Tower) - the key shown on the button.
function OnHotkey(key) {
	var portrait = Players.GetLocalPlayerPortraitUnit();
	$.Msg("[GTD] hotkey " + key + " portrait " + Entities.GetUnitName(portrait));
	var towerId = GTD.unit_to_tower[Entities.GetUnitName(portrait)];
	if (towerId) {
		var t = GTD.towers[towerId];
		if (Entities.GetPlayerOwnerID(portrait) !== Players.GetLocalPlayer()) { return; }
		for (var up in (t.upgrade_keys || {})) {
			if (t.upgrade_keys[up] === key) {
				selectedTower = portrait;
				DoUpgrade(up);
				return;
			}
		}
		return;
	}
	for (var i = 0; i < GTD.roots.length; i++) {
		var id = GTD.roots[i];
		if (GTD.towers[id].build_key === key) {
			StartBuild(id);
			return;
		}
	}
}

// Keys are read with GameUI.IsKeyDown (Game.CreateCustomKeyBind never fired in testing).
// Source button codes: KEY_0..KEY_9 = 1..10, KEY_A..KEY_Z = 11..36, ALT = 81/82, CONTROL = 83/84.
var KEY_ALT = [81, 82];
var KEY_CONTROL = [83, 84];
var hotkeyCodes = {};      // letter -> button code
var hotkeyWasDown = {};

function KeyCode(letter) {
	var c = letter.charCodeAt(0);
	if (c >= 48 && c <= 57) { return c - 48 + 1; }
	return c - 65 + 11;
}

function AnyDown(codes) {
	for (var i = 0; i < codes.length; i++) {
		if (GameUI.IsKeyDown(codes[i])) { return true; }
	}
	return false;
}

var chatInput = null;
var chatSearchAt = 0;
function ChatHasFocus() {
	if (!chatInput && Date.now() >= chatSearchAt) {
		// the HUD tree is big: look for the chat box at most every 2 seconds until it is found
		chatSearchAt = Date.now() + 2000;
		var root = $.GetContextPanel();
		while (root.GetParent()) { root = root.GetParent(); }
		chatInput = root.FindChildTraverse("ChatInput");
	}
	try {
		return chatInput !== null && chatInput.BHasKeyFocus();
	} catch (e) {
		return false;
	}
}

function PollHotkeys() {
	var blocked = ChatHasFocus() || AnyDown(KEY_ALT) || AnyDown(KEY_CONTROL);
	for (var key in hotkeyCodes) {
		var down = GameUI.IsKeyDown(hotkeyCodes[key]);
		if (down && !hotkeyWasDown[key] && !blocked) {
			OnHotkey(key);
		}
		hotkeyWasDown[key] = down;
	}
	$.Schedule(0.03, PollHotkeys);
}

function SetupHotkeys() {
	GTD.roots.forEach(function (id) {
		var k = GTD.towers[id].build_key;
		if (k) { hotkeyCodes[k] = KeyCode(k); }
	});
	for (var id in GTD.towers) {
		var uk = GTD.towers[id].upgrade_keys || {};
		for (var up in uk) { hotkeyCodes[uk[up]] = KeyCode(uk[up]); }
	}
	$.Msg("[GTD] hotkeys: " + Object.keys(hotkeyCodes).join(" "));
	PollHotkeys();
}

function UpdateTowerButtons() {
	var gold = MyGold();
	var container = $("#UpgradeButtons");
	for (var i = 0; i < container.GetChildCount(); i++) {
		var btn = container.GetChild(i);
		btn.SetHasClass("TooExpensive", gold < btn.costValue);
	}
	var build = $("#BuildButtons");
	for (var j = 0; j < build.GetChildCount(); j++) {
		var b = build.GetChild(j);
		var id = b.id.substring(6);
		b.SetHasClass("TooExpensive", GTD.towers[id] && gold < GTD.towers[id].cost);
	}
}

function GtdSell() {
	if (selectedTower !== -1) {
		GameEvents.SendCustomGameEventToServer("gtd_sell", { entindex: selectedTower });
	}
}

// ---------------------------------------------------------------- messages
function OnMessage(data) {
	var container = $("#Messages");
	var label = $.CreatePanel("Label", container, "");
	label.AddClass("Message");
	label.text = data.text;
	label.style.color = data.color || "#ffffff";
	$.Schedule(data.duration || 6, function () {
		if (!label.IsValid()) { return; }
		label.AddClass("Fade");
		$.Schedule(1, function () { if (label.IsValid()) { label.DeleteAsync(0); } });
	});
	if (container.GetChildCount() > 6) {
		container.GetChild(0).DeleteAsync(0);
	}
}

function OnError(data) {
	ShowError($.Localize(data.text));
}

